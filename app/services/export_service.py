"""
Export Service for CelebraTech AI Event Planner.
Provides downloadable Markdown summary reports, vendor CSV directories,
guest list CSVs, and complete JSON export payloads.
"""

from typing import Dict, Any
import io
import csv
from app.models.event import EventPlan
from app.services.budget_service import BudgetService


class ExportService:
    """Formats event plans for external sharing, printing, and vendor coordination."""

    @classmethod
    def generate_markdown_report(cls, event: EventPlan) -> str:
        """Generates a professional, structured Markdown report."""
        summary = BudgetService.calculate_summary(event)
        curr = event.currency

        lines = [
            f"# 🎪 Master Event Plan: {event.title}",
            f"**Event Type:** {event.event_type.value.capitalize()} | **Guests:** {event.guest_count} | **Date:** {event.date or 'TBD'} | **Location:** {event.location or 'TBD'}",
            f"**Theme:** {event.theme or 'N/A'} | **Vibe:** {event.vibe or 'N/A'}",
            "",
            "---",
            "",
            "## 💰 Financial & Budget Overview",
            f"- **Target Budget:** {curr} {summary.total_budget:,.2f}",
            f"- **Total Estimated:** {curr} {summary.total_estimated:,.2f}",
            f"- **Total Actual Paid/Invoiced:** {curr} {summary.total_actual:,.2f}",
            f"- **Remaining Balance:** {curr} {summary.remaining_budget:,.2f} ({100 - summary.percentage_spent:.1f}% remaining)",
            f"- **Budget Status:** {'⚠️ OVER BUDGET' if summary.is_over_budget else '✅ HEALTHY'}",
            "",
            "### Expense Breakdown by Category",
            "| Category | Estimated | Actual | % of Budget |",
            "| :--- | :--- | :--- | :--- |",
        ]

        for cat, data in summary.category_breakdown.items():
            lines.append(
                f"| {cat} | {curr} {data['estimated']:,.2f} | {curr} {data['actual']:,.2f} | {data['percentage_of_total']}% |"
            )

        lines.extend([
            "",
            "### Strategic Financial Recommendations",
        ])
        for rec in summary.cost_saving_recommendations:
            lines.append(f"- {rec}")

        lines.extend([
            "",
            "---",
            "",
            "## ⏱️ Timeline & Run of Show Schedule",
            "",
            "### 📅 Planning Milestones",
            "| Milestone | Target Time | Owner | Status |",
            "| :--- | :--- | :--- | :--- |",
        ])
        for item in [t for t in event.timeline_items if t.phase.value == "planning"]:
            status_str = "Completed ✅" if item.completed else "Pending ⏳"
            lines.append(f"| {item.title} | {item.time_or_offset} | {item.owner} | {status_str} |")

        lines.extend([
            "",
            "### ⏰ Day-of Run of Show",
            "| Time | Segment | Details | Lead |",
            "| :--- | :--- | :--- | :--- |",
        ])
        for item in [t for t in event.timeline_items if t.phase.value == "day_of"]:
            lines.append(f"| {item.time_or_offset} | **{item.title}** | {item.description} | {item.owner} |")

        lines.extend([
            "",
            "---",
            "",
            "## 🤝 Vendor Directory & Checklists",
            "| Category | Vendor Name | Quoted Price | Status | Action Tasks |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ])
        for v in event.vendors:
            tasks_str = f"{len(v.completed_tasks)}/{len(v.checklist_tasks)} complete"
            lines.append(f"| {v.category} | {v.name} | {curr} {v.quoted_price:,.2f} | {v.status.value} | {tasks_str} |")

        lines.extend([
            "",
            "---",
            "",
            "## 👥 Guest List & Seating Overview",
            "| Guest Name | Party | RSVP | Dietary | Table | Contact |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for g in event.guests:
            lines.append(f"| {g.name} | {g.party_size} | {g.rsvp_status.value} | {g.dietary} | {g.table_number or 'Unassigned'} | {g.email_or_phone or ''} |")

        lines.extend([
            "",
            "---",
            "",
            "## 💡 Curated AI Ideas & Styling",
        ])
        for idea in event.ideas:
            lines.extend([
                f"### {idea.title} *({idea.badge})*",
                f"**Concept:** {idea.description}",
                f"*Tagline:* {idea.tagline}",
                "**Key Highlights:**",
            ])
            for detail in idea.details:
                lines.append(f"- {detail}")
            lines.append("")

        lines.append("\n*Generated by CelebraTech AI Event Planning Engine.*")
        return "\n".join(lines)

    @classmethod
    def generate_budget_csv(cls, event: EventPlan) -> str:
        """Exports budget line items as CSV text."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["Category", "Item Name", "Estimated Cost", "Actual Cost", "Paid", "Notes"])
        for item in event.budget_items:
            writer.writerow([
                item.category,
                item.name,
                item.estimated_cost,
                item.actual_cost,
                "YES" if item.paid else "NO",
                item.notes or "",
            ])
        return output.getvalue()

    @classmethod
    def generate_vendors_csv(cls, event: EventPlan) -> str:
        """Exports vendors and checklist as CSV text."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["Category", "Vendor Name", "Status", "Quoted Price", "Completed Tasks", "All Tasks", "Notes"])
        for v in event.vendors:
            writer.writerow([
                v.category,
                v.name,
                v.status.value,
                v.quoted_price,
                "; ".join(v.completed_tasks),
                "; ".join(v.checklist_tasks),
                v.notes or "",
            ])
        return output.getvalue()

    @classmethod
    def generate_guests_csv(cls, event: EventPlan) -> str:
        """Exports guest list and RSVPs as CSV text."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["Guest Name", "Party Size", "RSVP Status", "Dietary Needs", "Table Number", "Contact", "Notes"])
        for g in event.guests:
            writer.writerow([
                g.name,
                g.party_size,
                g.rsvp_status.value,
                g.dietary,
                g.table_number or "",
                g.email_or_phone or "",
                g.notes or "",
            ])
        return output.getvalue()
