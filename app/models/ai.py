"""
Pydantic models for GenAI interactions, chat assistance, and dynamic generation.
"""

from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from app.models.event import (
    BudgetItem,
    TimelineItem,
    VendorItem,
    PersonalizedIdeaItem,
    GuestItem,
    ColorSwatch,
    EventType,
)


class AIPromptRequest(BaseModel):
    """Request payload for the GenAI assistant to create or augment an event plan."""
    event_type: EventType
    title: str = Field(..., min_length=2, max_length=150)
    budget: float = Field(..., ge=0.0)
    guest_count: int = Field(..., ge=1)
    location: Optional[str] = Field(default="", max_length=120)
    theme_preference: Optional[str] = Field(default="", max_length=150)
    vibe: Optional[str] = Field(default="", max_length=150)
    additional_notes: Optional[str] = Field(default="", max_length=1000)
    currency: str = Field(default="INR", max_length=5)


class AIChatMessage(BaseModel):
    """Single chat turn in conversation with the planning assistant."""
    role: str = Field(..., pattern="^(user|assistant|system)$")
    content: str = Field(..., min_length=1, max_length=4000)
    timestamp: Optional[str] = None


class AIChatRequest(BaseModel):
    """Interactive chat with the AI planner in context of a specific event."""
    event_id: str
    message: str = Field(..., min_length=1, max_length=2000)
    history: List[AIChatMessage] = Field(default_factory=list)


class AIChatResponse(BaseModel):
    """Response returned by the AI planner."""
    reply: str
    suggested_actions: List[str] = Field(default_factory=list)
    updated_event_data: Optional[Dict[str, Any]] = None


class AIIdeaGenerationRequest(BaseModel):
    """Targeted idea generation request for a specific sub-category."""
    event_type: EventType
    category: str = Field(..., pattern="^(theme|decor|menu|activities|playlist|invitation_copy)$")
    theme: Optional[str] = Field(default="", max_length=100)
    guest_count: int = Field(default=50, ge=1)
    budget_level: Optional[str] = Field(default="moderate", pattern="^(budget|moderate|luxury)$")


class AIPlanBundle(BaseModel):
    """Complete bundle generated by GenAI."""
    budget_items: List[BudgetItem]
    timeline_items: List[TimelineItem]
    vendors: List[VendorItem]
    ideas: List[PersonalizedIdeaItem]
    guests: List[GuestItem] = Field(default_factory=list)
    color_palette: List[ColorSwatch] = Field(default_factory=list)
    summary_advice: str
